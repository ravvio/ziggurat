const std = @import("std");

pub const Bitboard = u64;

pub fn debugPrint(b: Bitboard) void {
    std.debug.print("\n", .{});
    for (0..64) |i| {
        const a: u64 = @as(u64, 1) << @truncate(i);
        if (b & a == a) {
            std.debug.print("X ", .{});
        } else {
            std.debug.print(". ", .{});
        }
        if (i % 8 == 7) {
            std.debug.print("\n", .{});
        }
    }
}

pub const BitboardIterator = struct {
    u: Bitboard,

    pub fn new(u: Bitboard) BitboardIterator {
        return .{ .u = u };
    }

    pub fn next(self: *BitboardIterator) ?usize {
        if (self.u == 0) {
            return null;
        }
        const res = @ctz(self.u);
        self.u &= (self.u - 1);
        return res;
    }
};

pub fn toSquares(
    _bitboard: Bitboard,
    res: *[22]usize,
) void {
    var bitboard = _bitboard;
    var i: usize = 0;
    while (bitboard != 0) {
        res[i] = @ctz(bitboard);
        bitboard &= (bitboard - 1);
        i += 1;
    }
    res[i] = 64;
}

